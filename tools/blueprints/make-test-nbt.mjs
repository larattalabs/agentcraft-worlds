#!/usr/bin/env node
// Writes a tiny structure template (a 7x5x7 stone-brick room, glass window, door gap, one
// agentcraft:monitor and a desk) plus a matching sidecar, for exercising verify.mjs without the real
// generator.   node tools/blueprints/make-test-nbt.mjs [outDir] [id]
// DataVersion is read from the dev world's level.dat when it exists (else a fallback).
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { writeNbt, readNbt, int, str, byte, list, compound } from './nbt.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const outDir = path.resolve(process.argv[2] ?? path.join(root, 'artifacts', 'blueprint-test'));
const id = process.argv[3] ?? 'testroom';

function dataVersion() {
  try {
    const lvl = readNbt(fs.readFileSync(path.join(root, 'mod', 'run', 'saves', 'AgentCraft HQ', 'level.dat')));
    if (lvl.Data?.DataVersion) return lvl.Data.DataVersion;
  } catch {}
  return 4800;
}

const SX = 7, SY = 5, SZ = 7;
const palette = [];
const palIdx = (name, props) => {
  const key = name + JSON.stringify(props ?? {});
  let i = palette.findIndex((p) => p.key === key);
  if (i < 0) { palette.push({ key, name, props }); i = palette.length - 1; }
  return i;
};
const cells = new Map(); // "x,y,z" -> {state, nbt}
const put = (x, y, z, name, props, nbt) => cells.set(`${x},${y},${z}`, { state: palIdx(name, props), nbt });

for (let x = 0; x < SX; x++) for (let z = 0; z < SZ; z++) put(x, 0, z, 'minecraft:stone_bricks');
for (let y = 1; y < SY - 1; y++) {
  for (let x = 0; x < SX; x++) for (let z = 0; z < SZ; z++) {
    const wall = x === 0 || z === 0 || x === SX - 1 || z === SZ - 1;
    if (!wall) continue;
    if (z === SZ - 1 && x === 3 && y <= 2) continue; // door gap in the south wall
    if (y === 2 && (x === 0 || x === SX - 1) && z === 3) { put(x, y, z, 'minecraft:glass'); continue; }
    put(x, y, z, 'minecraft:oak_planks');
  }
}
for (let x = 0; x < SX; x++) for (let z = 0; z < SZ; z++) put(x, SY - 1, z, 'minecraft:spruce_slab', { type: 'bottom', waterlogged: 'false' });
// desk (a table of planks + slab) with a monitor on it facing south (towards +z), against the north wall
put(3, 1, 1, 'minecraft:spruce_planks');
put(3, 2, 1, 'agentcraft:monitor', { facing: 'south', lit: 'false', up: 'false', down: 'false', left: 'false', right: 'false' });
put(3, 1, 3, 'minecraft:spruce_stairs', { facing: 'north', half: 'bottom', shape: 'straight', waterlogged: 'false' }); // chair
put(1, 3, 1, 'minecraft:lantern', { hanging: 'false', waterlogged: 'false' });

const root_ = {
  DataVersion: int(dataVersion()),
  size: list('int', [SX, SY, SZ]),
  palette: list('compound', palette.map((p) => compound({
    id: str(p.name),
    ...(p.props ? { properties: compound(Object.fromEntries(Object.entries(p.props).map(([k, v]) => [k, str(v)]))) } : {}),
  }))),
  blocks: list('compound', [...cells].map(([k, c]) => {
    const [x, y, z] = k.split(',').map(Number);
    return compound({ pos: list('int', [x, y, z]), state: int(c.state), ...(c.nbt ? { nbt: c.nbt } : {}) });
  })),
  entities: list('compound', []),
};
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, `${id}.nbt`), writeNbt(root_));
const sidecar = {
  id, name: 'Test room', description: 'Generated by make-test-nbt.mjs', kind: 'single', wings: 1,
  size: { x: SX, y: SY, z: SZ }, groundY: 0, front: 'south', materials: 'vanilla',
  walk: { minX: 1, minY: 1, minZ: 1, maxX: SX - 2, maxY: SY - 2, maxZ: SZ - 2 },
  anchors: {
    desk_kit: { x: 3.5, y: 1.0, z: 2.5, yaw: 180, pitch: 0 }, // standing in front of the desk (z=2: air)
    seat_kit: { x: 3.5, y: 1.0, z: 3.5, yaw: 180, pitch: 0 }, // on the stairs (on the chair block: feet in a sittable block is fine)
    entrance: { x: 3.5, y: 1.0, z: 5.5, yaw: 0, pitch: 0 },
    spawn: { x: 3.5, y: 1.0, z: 4.5, yaw: 0, pitch: 0 },
    lounge: { x: 0.5, y: 1.0, z: 0.5, yaw: 0, pitch: 0 }, // deliberately inside the wall: should FAIL the check
    cam_overview: { x: 5.5, y: 3.5, z: 5.5, yaw: 135, pitch: 15, fov: 80 },
    cam_desk: { x: 3.5, y: 2.6, z: 4.5, yaw: 180, pitch: 5, fov: 70 },
  },
};
fs.writeFileSync(path.join(outDir, `${id}.blueprint.json`), JSON.stringify(sidecar, null, 2) + '\n');
console.log(`wrote ${path.join(outDir, id + '.nbt')} (+ .blueprint.json), DataVersion ${root_.DataVersion.v}`);
